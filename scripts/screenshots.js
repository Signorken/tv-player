// Screenshot per il README (docs/screenshots). Richiede: node companion/server.js, node test/mock.js, node test/demo.js
const puppeteer = require('puppeteer-core');
const path = require('path'), fs = require('fs');
const OUT = path.join(__dirname, '..', 'docs', 'screenshots'); fs.mkdirSync(OUT, { recursive: true });
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const b = await puppeteer.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', headless: 'new', env: Object.assign({}, process.env, { LANG: 'it_IT.UTF-8', LANGUAGE: 'it' }), args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'], defaultViewport: { width: 1920, height: 1080 } });
  const p = await b.newPage();
  const key = async (k, n) => { for (let i = 0; i < (n || 1); i++) { await p.keyboard.press(k); await sleep(160); } };
  const wait = (fn, ms) => p.waitForFunction(fn, { timeout: ms || 15000, polling: 150 }).catch(() => null);
  const shot = async n => { await sleep(500); await p.screenshot({ path: path.join(OUT, n + '.jpg'), type: 'jpeg', quality: 82 }); console.log('  ' + n); };
  const home = async () => { await p.evaluate(() => { const M = window.__app.Mini; if (M.player) M.close(); window.__app.router.home(); }); await sleep(600); };
  await p.goto('http://localhost:8787/app/'); await sleep(500);
  await p.evaluate(() => {
    localStorage.clear();
  });
  await p.reload(); await sleep(600);
  await p.evaluate(() => {
    const s = window.__app.store, st = s.settings();
    st.proxyMedia = true; st.lowPower = true; st.sounds = false; st.layout = 'A';
    s.addSource({ id: 'demo', type: 'xtream', name: 'Demo IPTV', url: 'http://localhost:9110', user: 'demo', pass: 'demo', epgMode: 'short' });
    s.setActive('demo');
    const add = (kind, id, name, poster, sub, pos, dur) => { const k = s.favKey('demo', kind, id); s.addRecent(k, { kind: kind, src: 'demo', id: id, name: name, poster: poster, logo: poster, sub: sub, ext: 'mp4' }); if (pos) s.setProgress(k, pos, dur); };
    ['Aurora 1', 'Prisma News', 'Delta Sport', 'Cinema Uno', 'Musica Viva'].forEach((n, i) => { const id = String([1, 4, 5, 7, 9][i]); s.addRecent(s.favKey('demo', 'live', id), { kind: 'live', src: 'demo', id: id, name: n, logo: 'http://localhost:9110/img/c' + [0, 3, 4, 6, 8][i] + '.png' }); });
    add('movie', '505', 'Ombre di Città', 'http://localhost:9110/img/m5.jpg', '2020', 1500, 6300);
    add('movie', '501', 'Ultima Corsa', 'http://localhost:9110/img/m1.jpg', '2016', 3200, 6000);
    add('movie', '508', 'Il Giardino di Vetro', 'http://localhost:9110/img/m8.jpg', '2023', 900, 5400);
    add('movie', '503', 'Il Codice Aurora', 'http://localhost:9110/img/m3.jpg', '2018', 4100, 6200);
    add('movie', '500', 'Il Faro del Nord', 'http://localhost:9110/img/m0.jpg', '2015', 2000, 5600);
    ['502', '506', '509'].forEach((id, i) => s.toggleList(s.favKey('demo', 'movie', id), { kind: 'movie', src: 'demo', id: id, name: ['Luci su Milano', 'La Strada del Sale', 'Rotta 66'][i], poster: 'http://localhost:9110/img/m' + id.slice(2) + '.jpg' }));
    s.save(true);
  });
  await p.reload(); await sleep(2000);
  await shot('01-home');
  await key('ArrowLeft'); await sleep(500); await shot('02-barra-laterale'); await key('ArrowRight');
  await p.evaluate(() => window.__app.router.current.openVod('movie', 'all'));
  await wait(() => window.__app.router.current.items && window.__app.router.current.items.length > 3);
  await p.evaluate(() => { const c = window.__app.router.current; const i = c.catList.findIndex(x => x.name === 'Drammatico'); if (i >= 0) { c.cats.select(i); c.catOk(c.catList[i]); } });
  await sleep(1500); await key('ArrowRight'); await sleep(1500);
  await shot('03-on-demand');
  await key('Enter'); await wait(() => document.querySelector('.screen.detail .dbtns .btn')); await sleep(1500);
  await shot('04-scheda-film');
  await home();
  await p.evaluate(() => window.__app.router.current.openLive());
  await wait(() => window.__app.router.current.all); await sleep(800);
  await key('ArrowDown', 3); await sleep(800);
  await shot('05-tv-in-diretta');
  await key('Enter'); await wait(() => { const v = document.querySelector('video.pv'); return v && v.currentTime > 0.5; }); await sleep(1500);
  await shot('06-player');
  await sleep(5500); await key('ArrowLeft'); await sleep(700);
  await shot('07-player-canali');
  await key('Escape'); await key('ArrowRight'); await sleep(700);
  await shot('08-player-opzioni');
  await key('Escape'); await sleep(300); await key('Escape'); await sleep(800);
  await p.evaluate(() => window.__app.router.home()); await sleep(1200);
  await shot('09-finestrella');
  await home();
  await p.evaluate(() => { const s = window.__app.store.settings(); s.layout = 'B'; window.__app.applyUi(); window.__app.router.current.refresh(); window.__app.nav.focus(document.querySelector('.home .tile')); });
  await sleep(800); await shot('10-home-aspetto-b');
  await p.evaluate(() => { const s = window.__app.store.settings(); s.layout = 'A'; window.__app.applyUi(); window.__app.router.current.refresh(); });
  await p.evaluate(() => window.__app.router.current.openSettings()); await sleep(600);
  await p.evaluate(() => { const c = [].slice.call(document.querySelectorAll('.scat')).find(x => /Aspetto/.test(x.textContent)); c.click(); }); await sleep(500);
  await shot('11-impostazioni');
  await home();
  await p.evaluate(() => window.__app.router.current.openLive());
  await wait(() => window.__app.router.current.all); await sleep(500);
  await p.evaluate(() => window.__app.router.current.openGuide()); await sleep(2500); await key('ArrowDown', 2); await sleep(1200);
  await shot('12-guida-tv');
  await home();
  await p.evaluate(() => window.__app.router.current.openSearch()); await sleep(600);
  await p.keyboard.type('il'); await key('Enter'); await wait(() => document.querySelectorAll('.screen.search .ccard').length > 2); await sleep(1500);
  await shot('13-ricerca');
  await home();
  await p.evaluate(() => { const s = window.__app.store.settings(); s.theme = 'light'; s.wallpaper = 'l1-alba'; window.__app.applyUi(); window.__app.router.current.refresh(); });
  await sleep(1500); await shot('14-tema-chiaro');
  await p.evaluate(() => { const s = window.__app.store.settings(); s.theme = 'dark'; s.wallpaper = '01-aurora'; window.__app.applyUi(); });
  await b.close();
})().catch(e => { console.error(e); process.exit(1); });
